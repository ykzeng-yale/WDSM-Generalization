equal <- function(actual, expected, tolerance = 1e-11) {
  result <- all.equal(unname(actual), unname(expected), tolerance = tolerance,
                      check.attributes = FALSE)
  if (!isTRUE(result)) stop(paste(result, collapse = "; "), call. = FALSE)
}
fails <- function(expression, pattern) {
  message <- tryCatch({ force(expression); NULL }, error = conditionMessage)
  if (is.null(message) || !grepl(pattern, message)) {
    stop("Expected an error matching: ", pattern, call. = FALSE)
  }
}
bit_rows <- function(k) {
  if (k == 0L) return(matrix(integer(), 1L, 0L))
  as.matrix(expand.grid(rep(list(0:1), k)))
}
bit_probability <- function(bits, p) {
  apply(bits, 1L, function(row) prod(ifelse(row == 1L, p, 1 - p)))
}

# Exhaustive labeled Bernoulli tuples independently check the binomial
# grouping and conditional-private-set factorization used by the routine.
for (M in 1:4) for (p in c(0, 0.23, 0.7, 1)) {
  w <- c(0.7, 2.9)
  marks <- wm_two_point_mark_moments(M, w, p)
  private <- bit_rows(M - 1L)
  probability <- bit_probability(private, p)
  sums <- apply(private, 1L, function(row) sum(w[row + 1L]))
  for (root in 1:2) {
    share <- w[root] / (w[root] + sums)
    equal(marks$A[root], sum(probability * share))
    equal(marks$B[root], sum(probability * share^2))
    for (ell in 0:(M - 1L)) {
      a <- M - 1L - ell
      tuples <- bit_rows(ell + 2L * a)
      tuple_probability <- bit_probability(tuples, p)
      terms <- apply(tuples, 1L, function(row) {
        shared <- sum(w[row[seq_len(ell)] + 1L])
        first <- sum(w[row[ell + seq_len(a)] + 1L])
        second <- sum(w[row[ell + a + seq_len(a)] + 1L])
        w[root]^2 / ((w[root] + shared + first) * (w[root] + shared + second))
      })
      equal(marks$C[root, ell + 1L], sum(tuple_probability * terms))
    }
  }
  equal(sum(c(1 - p, p) * marks$A), 1 / M)
  equal(marks$C[, M], marks$B)
}

