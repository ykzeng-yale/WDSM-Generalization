  one <- wm_two_point_mark_moments(1, c(0.2, 7), 0.4)
  equal(c(one$A, one$B, one$C), rep(1, 6))

  # The ordinary unweighted coefficient 1+K/M is a separate variance check.
  q <- 0.3
  variance <- c(0.6, 1.7)
  h <- 0.2
  result <- wm_benchmark_strong(M, beta, matrix(0, M, M), q = q,
    weight0 = c(1, 1), weight1 = c(1, 1),
    variance0 = rep(variance[1], 2), variance1 = rep(variance[2], 2),
    effect_variance = h)
  arm_probability <- c(1 - q, q)
  r <- rev(arm_probability) / arm_probability
  alpha <- M^2 + M / 2
  expected_a <- h + sum(arm_probability * variance *
    (1 + 2 * r + r / M + alpha * r^2 / M^2))
  expected_t <- (q * (h + variance[2]) +
    (1 - q) * variance[1] * (r[1] / M + alpha * r[1]^2 / M^2)) / q^2
  equal(result$table$root_n_variance, rep(c(expected_a, expected_t), 2))
  equal(result$table$geometry_mcse, rep(0, 4))
}
