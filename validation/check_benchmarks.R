# Linear sensitivity to geometry and full covariance propagation, including
# correlations between different overlap estimates.
M <- 3L
beta <- wm_beta_1d(M)
covariance <- diag(c(0.01, 0.02, 0.03)) + tcrossprod(c(0.02, 0.03, -0.01))
for (benchmark in list(wm_benchmark_strong, wm_benchmark_weak)) {
  result <- benchmark(M, beta, covariance)
  rows <- which(result$table$variance_scope == "bias_corrected")
  for (i in rows) {
    coefficient <- result$beta_coefficients[i, ]
    expected <- sqrt(as.numeric(crossprod(coefficient, covariance %*% coefficient)))
    equal(result$table$geometry_mcse[i], expected)
  }
  for (j in seq_len(M)) {
    changed <- beta
    changed[j] <- changed[j] + 1e-5
    perturbed <- benchmark(M, changed, covariance)
    derivative <- (perturbed$table$root_n_variance[rows] -
                     result$table$root_n_variance[rows]) / 1e-5
    equal(derivative, result$beta_coefficients[rows, j], tolerance = 1e-8)
  }
  unknown <- benchmark(M, beta)
  stopifnot(all(is.na(unknown$table$geometry_mcse[rows])))
}
